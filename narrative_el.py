# Unique trap for EVERY sun-moon pair (the thing that actually differs)
def _trap(sun: ZodiacSignId, moon: ZodiacSignId) -> str:
    key = (sun, moon)
    special = PAIR_TRAP.get(key)
    if special:
        return special
    # Fallback still names both signs so charts never sound identical
    sw = SUN_WANT[sun]
    mn = MOON_NEED[moon]
    sun_n = get_zodiac_by_id(sun).name_el
    moon_n = get_zodiac_by_id(moon).name_el
    return (
        f"Ο Ήλιος στον/στην/στους {sun_n} σε σπρώχνει να {sw}. "
        f"Η Σελήνη στον/στην/στους {moon_n} όμως, όταν στρεσάρεσαι, ζητάει άλλο πράγμα: {mn}. "
        f"Το μπέρδεμα ξεκινάει όταν κυνηγάς μόνο το ένα και αγνοείς το άλλο."
    )


