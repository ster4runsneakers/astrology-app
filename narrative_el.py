def build_rich_summary(
    sun_id: ZodiacSignId,
    moon_id: ZodiacSignId,
    asc_id: ZodiacSignId | None = None,
    name: str = "",
) -> str:
    sun = get_zodiac_by_id(sun_id)
    moon = get_zodiac_by_id(moon_id)
    who = name.strip() if name else "Εσύ"

    se, me = _ELEMENT[sun_id], _ELEMENT[moon_id]
    tip = _ELEM_TIP.get((se, me), "")
    trap = PAIR_TRAP.get((sun_id, moon_id))
    if not trap:
        trap = (
            f"Θέλεις {SUN_WANT[sun_id]}. "
            f"Όταν στρεσάρεσαι, χρειάζεσαι {MOON_NEED[moon_id]}. "
            f"{tip}"
        )

    scene = SUN_SCENE[sun_id]
    parts = [
        f"### Σε απλά λόγια\n"
        f"**{who}**: ο {sun_in_sign(sun_id)} δείχνει τι κυνηγάς στη ζωή — {SUN_WANT[sun_id]}. "
        f"Η {moon_in_sign(moon_id)} δείχνει τι χρειάζεσαι για να ηρεμήσεις — {MOON_NEED[moon_id]}.",

        f"### Το μοτίβο που σε μπερδεύει\n"
        f"{trap}",

        f"### Παράδειγμα από την καθημερινότητα\n"
        f"{scene} "
        f"Αν αγνοήσεις τη Σελήνη ({moon.name_el}), μένεις σφιγμένος ακόμα κι αν «κέρδισες» τη συζήτηση. "
        f"**Κάνε αυτό:** πρώτα φρόντισε αυτό που χρειάζεσαι για ηρεμία ({MOON_NEED[moon_id]}), "
        f"και μετά μία καθαρή ενέργεια προς αυτό που κυνηγάς ({SUN_WANT[sun_id]}).",
    ]

    if asc_id:
        parts.append(
            f"### Πώς σε βλέπουν οι άλλοι\n"
            f"Ο {asc_in_sign(asc_id)} είναι η πρώτη εντύπωση: σε βλέπουν ως "
            f"**{ASC_LOOK[asc_id]}**. "
            f"Αυτό δεν είναι πάντα αυτό που νιώθεις μέσα σου "
            f"(Ήλιος {sun.name_el} / Σελήνη {moon.name_el}). "
            f"Γι’ αυτό μερικές φορές λες «δεν με καταλαβαίνουν» — βλέπουν τη βιτρίνα, όχι όλο το πακέτο."
        )
    else:
        parts.append(
            "### Πώς σε βλέπουν οι άλλοι\n"
            "Χωρίς ακριβή **ώρα γέννησης** δεν βγαίνει ο Ωροσκόπος (η πρώτη εντύπωση). "
            "Βάλε ώρα αν μπορείς — η ανάγνωση γίνεται πολύ πιο συγκεκριμένη."
        )

    parts.append(
        f"### Τι να κάνεις αυτή την εβδομάδα\n"
        f"{_week_action(sun_id, moon_id)}"
    )

    parts.append(
        f"### Μία πρόταση να θυμάσαι\n"
        f"**{sun.name_el} σε κίνηση + {moon.name_el} σε φροντίδα = ισορροπία.** "
        f"Όχι το ένα αντί για το άλλο."
    )

    return "\n\n".join(parts)
