def build_rich_summary(
    sun_id: ZodiacSignId,
    moon_id: ZodiacSignId,
    asc_id: Optional[ZodiacSignId],
    name: str = "",
) -> str:
    sun = get_zodiac_by_id(sun_id)
    moon = get_zodiac_by_id(moon_id)
    who = f"{name}," if name else "Λοιπόν,"

    p0 = (
        f"{who} άσε με να σου πω κάτι καθαρά — χωρίς αστρολογικό «νερόβρασμα». "
        f"Ο **Ήλιος στον {sun.name_el}** δείχνει ποιος είσαι όταν σταθείς όρθιος στον κόσμο: "
        f"{SUN_PUNCH[sun_id]}."
    )
    p1 = (
        f"Η **Σελήνη στον {moon.name_el}** όμως είναι η νυχτερινή σου αλήθεια — "
        f"εκεί που επιστρέφεις όταν κλείσει η πόρτα: {MOON_PUNCH[moon_id]}."
    )

    se, me = ELEMENT_OF[sun_id], ELEMENT_OF[moon_id]
    if sun_id == moon_id:
        p2 = (
            f"Ήλιος και Σελήνη στο **ίδιο ζώδιο** ({sun.name_el}) — δυνατός, καθαρός χαρακτήρας. "
            f"Οι άλλοι σε διαβάζουν σχετικά εύκολα· εσύ όμως πρέπει να προσέχεις μην γίνεις "
            f"«πολύ από το ίδιο» χωρίς αντίβαρο. Ζήτα ποικιλία στη ζωή σου συνειδητά."
        )
    else:
        story = ELEMENT_STORY.get((se, me))
        if story:
            p2 = story
        else:
            p2 = (
                f"Με Ήλιο σε στοιχείο **{sun.element_el}** και Σελήνη σε **{moon.element_el}**, "
                f"ζεις έναν εσωτερικό διάλογο ανάμεσα στο «ποιος είμαι» και στο «τι χρειάζομαι». "
                f"Μην διαλέγεις μόνο τη μία πλευρά· η δύναμή σου είναι η γέφυρα."
            )

    if asc_id:
        asc = get_zodiac_by_id(asc_id)
        p3 = (
            f"Και μετά έρχεται ο **Ωροσκόπος στον {asc.name_el}** — η βιτρίνα, το πρώτο χαμόγελο, "
            f"το πώς σε συστήνει η ζωή πριν προλάβεις να εξηγήσεις: {ASC_PUNCH[asc_id]} "
            f"Πολλοί βλέπουν αυτό· λίγοι φτάνουν στον Ήλιο και τη Σελήνη σου. Διάλεξε ποιους αφήνεις να περάσουν."
        )
    else:
        p3 = (
            "Χωρίς ακριβή **ώρα γέννησης** δεν ανοίγει ο Ωροσκόπος — κι είναι κρίμα, γιατί εκεί "
            "φαίνεται το προσωπείο με το οποίο μπαίνεις στις σχέσεις και στη δουλειά. "
            "Αν μπορείς, συμπλήρωσέ την· η ανάγνωση γίνεται πιο «εσύ»."
        )

    p4 = (
        "Τι να κρατήσεις πρακτικά; Όταν νιώθεις χαμένος, ρώτα: "
        f"*τι θα έκανε ο {sun.name_el} μέσα μου* (Ήλιος) και "
        f"*τι χρειάζεται ο {moon.name_el} μου για να ηρεμήσει* (Σελήνη). "
        "Αν απαντήσεις και στα δύο χωρίς να προδώσεις το ένα, είσαι σε καλό δρόμο. "
        "Η αστρολογία εδώ δεν σε κλειδώνει· σου δίνει γλώσσα για να μιλήσεις στον εαυτό σου."
    )

    return "\n\n".join([p0, p1, p2, p3, p4])
