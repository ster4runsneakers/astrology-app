def build_rich_summary(
    sun_id: ZodiacSignId,
    moon_id: ZodiacSignId,
    asc_id: ZodiacSignId | None = None,
    name: str = "",
) -> str:
    sun = get_zodiac_by_id(sun_id)
    moon = get_zodiac_by_id(moon_id)
    who = f"{name}," if name else "Λοιπόν,"

    p0 = (
        f"{who} άσε με να σου πω κάτι καθαρά — χωρίς αστρολογικό «νερόβρασμα».\n\n"
        f"Ο **{sun_in_sign(sun_id)}** δείχνει ποιος είσαι όταν σταθείς όρθιος στον κόσμο: "
        f"{SUN_CORE[sun_id]}.\n\n"
        f"{SUN_EXAMPLE[sun_id]}"
    )
    p1 = (
        f"Η **{moon_in_sign(moon_id)}** είναι η νυχτερινή σου αλήθεια — "
        f"εκεί που επιστρέφεις όταν κλείσει η πόρτα: {MOON_CORE[moon_id]}.\n\n"
        f"{MOON_EXAMPLE[moon_id]}"
    )

    se, me = ELEMENT_OF[sun_id], ELEMENT_OF[moon_id]
    if sun_id == moon_id:
        p2 = (
            f"Ήλιος και Σελήνη στο **ίδιο ζώδιο** ({sun.name_el}) — δυνατό, καθαρό μοτίβο. "
            f"Οι άλλοι σε διαβάζουν εύκολα· εσύ χρειάζεσαι συνειδητά ποικιλία.\n\n"
            f"**Παράδειγμα:** αν όλα στη ζωή σου είναι «{sun.name_el}-mode», βαριέσαι ή υπερβάλλεις. "
            f"**Λύση:** βάλε μία δραστηριότητα έξω από το στοιχείο σου κάθε εβδομάδα."
        )
    else:
        p2 = ELEMENT_STORY.get(
            (se, me),
            (
                f"Με Ήλιο σε **{sun.element_el}** και Σελήνη σε **{moon.element_el}**, "
                f"ζεις διάλογο ανάμεσα στο «ποιος είμαι» και στο «τι χρειάζομαι». "
                f"Η δύναμή σου είναι η γέφυρα — όχι η επιλογή μίας μόνο πλευράς."
            ),
        )

    if asc_id:
        p3 = (
            f"Και μετά έρχεται ο **{asc_in_sign(asc_id)}** — η βιτρίνα, το πρώτο χαμόγελο, "
            f"το πώς σε συστήνει η ζωή πριν προλάβεις να εξηγήσεις: {ASC_CORE[asc_id]} "
            f"Πολλοί βλέπουν αυτό· λίγοι φτάνουν στον Ήλιο και τη Σελήνη σου. "
            f"Διάλεξε ποιους αφήνεις να περάσουν.\n\n"
            f"{ASC_EXAMPLE[asc_id]}"
        )
    else:
        p3 = (
            "Χωρίς ακριβή **ώρα γέννησης** δεν ανοίγει ο Ωροσκόπος — κι είναι κρίμα, "
            "γιατί εκεί φαίνεται το προσωπείο με το οποίο μπαίνεις στις σχέσεις και στη δουλειά. "
            "Αν μπορείς, συμπλήρωσέ την· η ανάγνωση γίνεται πιο «εσύ»."
        )

    p4 = (
        "### Τι να κάνεις όταν νιώθεις χαμένος\n\n"
        f"1. Ρώτα: *τι θα έκαναν {the_sign_inside(sun_id)}* (Ήλιος — ταυτότητα/δράση).\n"
        f"2. Ρώτα: *τι χρειάζονται {my_sign_needs(moon_id)} για να ηρεμήσουν* (Σελήνη — ασφάλεια).\n"
        "3. Κάνε **μία** μικρή πράξη από το (1) και **μία** από το (2) την ίδια μέρα.\n\n"
        f"**Παράδειγμα για σένα:** αν ο Ήλιος ζητάει βάθος/{sun.name_el} και η Σελήνη χώρο/"
        f"{moon.name_el}, μπορεί να σημαίνει: ένα ειλικρινές μήνυμα σε κάποιον που νοιάζεσαι "
        f"**και** μία ώρα χωρίς ειδοποιήσεις. Όχι το ένα αντί για το άλλο.\n\n"
        "Η αστρολογία εδώ δεν σε κλειδώνει· σου δίνει γλώσσα και ασκήσεις για να μιλήσεις στον εαυτό σου."
    )

    return "\n\n".join([p0, p1, p2, p3, p4])
