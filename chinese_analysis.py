@dataclass
class ChineseAnalysis:
    headline_el: str
    body_el: str
    love_el: str
    work_el: str
    gift_el: str
    shadow_el: str
    tips: List[str]


def analyze_chinese(cz: ChineseZodiac, name: str = "") -> ChineseAnalysis:
    deep = ANIMAL_DEEP.get(cz.animal_id, ANIMAL_DEEP["horse"])
    elem = ELEMENT_VOICE.get(cz.element_el, "")
    yy = YIN_YANG.get(cz.polarity, "")
    who = f"{name}, " if name else ""

    headline = f"{cz.symbol} {cz.animal_el} · {cz.element_el} ({cz.polarity}) · {cz.lunar_year}"
    body = (
        f"{who}στο κινεζικό σου πορτρέτο δεν είσαι απλά ένα ζώδιο. "
        f"Είσαι **{cz.animal_el}** γεννημένος σε χρονιά **{cz.element_el}** — "
        f"και αυτό μετράει.\n\n"
        f"{cz.traits_el}\n\n{elem}\n\n{yy}"
    )
    tips = [
        f"Όταν αποφασίζεις, ρώτα: τι θα τιμούσε τον {cz.animal_el} μέσα μου;",
        f"Τόνισε το στοιχείο **{cz.element_el}** με μικρές τελετουργίες της καθημερινότητας.",
        "Για συναστρία: δες αν ο άλλος είναι στο τρίγωνό σου ή στην αντίθεσή σου — χάρτης, όχι καταδίκη.",
    ]
    return ChineseAnalysis(
        headline_el=headline,
        body_el=body,
        love_el=deep["love"],
        work_el=deep["work"],
        gift_el=deep["gift"],
        shadow_el=deep["shadow"],
        tips=tips,
    )
