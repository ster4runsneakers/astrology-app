YIN_YANG = {
    "Yang": "Η **Yang** πλευρά σου είναι εξωστρεφής, ενεργητική, θέλει να φαίνεται και να δρα.",
    "Yin": "Η **Yin** πλευρά σου είναι πιο εσωτερική, δεκτική, παρατηρεί πριν κινηθεί — και συχνά νικά με ησυχία.",
}


@dataclass
class ChineseAnalysis:
    headline_el: str
    body_el: str
    love_el: str
    work_el: str
    gift_el: str
    shadow_el: str
    tips: List[str]


def analyze_chinese(cz: ChineseZodiac, name: str = "") -> ChineseAnalysis:
    deep = ANIMAL_DEEP.get(cz.animal_id, ANIMAL_DEEP["horse"])
    elem = ELEMENT_VOICE.get(cz.element_el, "")
    yy = YIN_YANG.get(cz.polarity, "")
    who = f"{name}, " if name else ""

    headline = f"{cz.symbol} {cz.animal_el} · {cz.element_el} ({cz.polarity}) · {cz.lunar_year}"
    body = (
        f"{who}στο κινεζικό ημερολόγιο γεννήθηκες χρονιά **{cz.animal_el}** "
        f"με στοιχείο **{cz.element_el}** ({cz.polarity}).\n\n"
        f"**Τι σημαίνει απλά:** {cz.traits_el}\n\n"
        f"{elem}\n\n{yy}\n\n"
        f"**Καθημερινό παράδειγμα:** όταν στρεσάρεσαι, ο {cz.animal_el} μέσα σου "
        f"θέλει {'κίνηση και καινούργια ιδέα' if cz.animal_id in ('monkey','horse','tiger','rat') else 'τάξη, σχέδιο ή σιγουριά'}. "
        f"Αν σε πιέζουν χωρίς νόημα, αντιδράς με αποφυγή ή πείσμα."
    )
    love = (
        f"{deep['love']}\n\n"
        f"**Παράδειγμα:** αν βαριέσαι στη σχέση, μην εξαφανιστείς. "
        f"Πες καθαρά τι λείπει και πρότεινε κάτι συγκεκριμένο αυτή την εβδομάδα."
    )
    work = (
        f"{deep['work']}\n\n"
        f"**Παράδειγμα:** διάλεξε ρόλο όπου αλλάζει το πρόβλημα — "
        f"όχι μόνο ίδια ρουτίνα χωρίς νόημα, αλλιώς σβήνει το κίνητρο."
    )
    tips = [
        f"Ρώτα πριν αποφασίσεις: «τι θα τιμούσε τον {cz.animal_el} μέσα μου;»",
        f"Στήριξε το στοιχείο **{cz.element_el}** με μικρή σταθερή ρουτίνα (ύπνος, τάξη χώρου, ή άσκηση).",
        f"Άσκηση 7 ημερών: κάθε βράδυ μία φορά που φάνηκε το δώρο του {cz.animal_el} και μία η σκιά.",
    ]
    return ChineseAnalysis(
        headline_el=headline,
        body_el=body,
        love_el=love,
        work_el=work,
        gift_el=deep["gift"],
        shadow_el=deep["shadow"] + "\n\n**Παράδειγμα σκιάς:** ξεκινάς με ενθουσιασμό και αφήνεις στη μέση — πες σε έναν φίλο ένα μικρό deadline.",
        tips=tips,
    )
