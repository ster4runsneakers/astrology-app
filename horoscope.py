def _hash_string(s: str) -> int:
    h = 2166136261
    for ch in s:
        h ^= ord(ch)
        h = (h * 16777619) & 0xFFFFFFFF
    return h


def _pick(arr: Sequence[str], seed: int, salt: int) -> str:
    idx = (seed + salt * 2654435761) % len(arr)
    return arr[idx]


def _date_label_el(d: date) -> str:
    # Monday=0 in Python weekday()
    return f"{_GREEK_WEEKDAYS[d.weekday()]}, {d.day} {_GREEK_MONTHS[d.month]} {d.year}"


@dataclass(frozen=True)
class DailyHoroscope:
    sign_id: ZodiacSignId
    sign_el: str
    symbol: str
    date_iso: str
    date_label_el: str
    text: str
    theme: str
    disclaimer_el: str


def get_daily_horoscope(sign_id: ZodiacSignId, when: date | None = None) -> DailyHoroscope:
    """Deterministic Greek daily horoscope from sign + calendar date."""
    when = when or date.today()
    z = get_zodiac_by_id(sign_id)
    date_iso = when.isoformat()
    seed = _hash_string(f"{sign_id}:{date_iso}")

    opener = _pick(OPENERS[sign_id], seed, 1)
    theme = _pick(THEMES, seed, 2)
    middle = _pick(MIDDLES, seed, 3).replace("{theme}", theme)
    closer = _pick(CLOSERS, seed, 4)

    return DailyHoroscope(
        sign_id=sign_id,
        sign_el=z.name_el,
        symbol=z.symbol,
        date_iso=date_iso,
        date_label_el=_date_label_el(when),
        text=f"{opener} {middle} {closer}",
        theme=theme,
        disclaimer_el=DISCLAIMER_EL,
    )
