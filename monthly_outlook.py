@dataclass
class MonthCard:
    year: int
    month: int
    label_el: str
    theme_el: str
    text_el: str


@dataclass
class MonthlyOutlook:
    months: List[MonthCard]
    chinese_note_el: str
    disclaimer_el: str
    source: str


def _next_months(start: date, count: int) -> List[Tuple[int, int]]:
    y, m = start.year, start.month
    out: List[Tuple[int, int]] = []
    for _ in range(count):
        out.append((y, m))
        m += 1
        if m > 12:
            m = 1
            y += 1
    return out


def build_monthly_outlook(
    sun_id: ZodiacSignId,
    chinese: Optional[ChineseZodiac] = None,
    start: Optional[date] = None,
    months: int = 6,
) -> MonthlyOutlook:
    start = start or date.today()
    months = max(3, min(6, int(months)))
    z = get_zodiac_by_id(sun_id)
    flavor = SIGN_FLAVOR.get(sun_id, "Με τον Ήλιο σου ενεργό")
    sun_off = sum(ord(c) for c in sun_id) % len(THEME_PACKS)
    cards: List[MonthCard] = []

    for i, (y, m) in enumerate(_next_months(start, months)):
        pack = THEME_PACKS[(i + sun_off) % len(THEME_PACKS)]
        theme, attention, practical, example, closer, _tid = pack
        opener = OPENERS[(i + m) % len(OPENERS)]
        season = SEASON_HINT.get(m, "μεταβατική ενέργεια")

        text = (
            f"{opener} **{z.name_el}**.\n\n"
            f"{flavor}, ο **{MONTHS_EL[m]} {y}** έχει αέρα «{season}». "
            f"Κύριο θέμα: **{theme}**. Η προσοχή σου πέφτει φυσικά {attention}.\n\n"
            f"**Πρακτικά:** {practical}\n\n"
            f"**{example}**\n\n"
            f"**Συμβουλή μήνα:** {closer}"
        )
        cards.append(
            MonthCard(
                year=y,
                month=m,
                label_el=f"{MONTHS_EL[m]} {y}",
                theme_el=theme,
                text_el=text,
            )
        )

    if chinese:
        cn_note = (
            f"**Κινεζική γραμμή για όλη την περίοδο:** {chinese.symbol} {chinese.animal_el} · "
            f"{chinese.element_el} ({chinese.polarity}) · σεληνιακό {chinese.lunar_year}. "
            f"{chinese.traits_el} "
            f"Στους επόμενους μήνες, στήριξε αποφάσεις στο στοιχείο **{chinese.element_el}** "
            f"(σταθερότητα/ρυθμός/ποιότητα) αντί να πας κόντρα του."
        )
    else:
        cn_note = ""

    return MonthlyOutlook(
        months=cards,
        chinese_note_el=cn_note,
        disclaimer_el=DISCLAIMER_EL,
        source="local",
    )
